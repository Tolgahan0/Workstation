/// Yerelleştirilmiş metin. `args` sırayla "%@" yer tutucularına yazılır.
func L(_ key: String, _ args: Any...) -> String {
    var s = L10n.translate(key)
    for a in args {
        guard let r = s.range(of: "%@") else { break }
        s.replaceSubrange(r, with: "\(a)")
    }
    return s
}
